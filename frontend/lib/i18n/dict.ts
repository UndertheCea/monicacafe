export const DICTS: Record<Locale, Messages> = { "zh-TW": zhTW, en };

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

/** Translate `key` for `locale`, interpolating `{name}` placeholders. */
export function t(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const msg = DICTS[locale][key] ?? DICTS[DEFAULT_LOCALE][key];
  if (!vars) return msg;
  return msg.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in vars ? String(vars[name]) : m,
  );
}

/** Locale from `<html lang>` (set by the root layout), for client components with no locale prop. */
export function localeFromLang(lang: string | null | undefined): Locale {
  return isLocale(lang) ? lang : DEFAULT_LOCALE;
}

/** Pick the zh or en variant of a bilingual DB field. */
export function pick(locale: Locale, zh: string, en: string): string {
  return locale === "en" ? en : zh;
}
